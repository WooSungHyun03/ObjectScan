import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";
const tokens = JSON.parse(
  await readFile("apps/web/src/lib/design-tokens/tokens.json", "utf8"),
);
const css = await format(
  `/* Generated by scripts/sync-design-system.mjs; edit lib/design-tokens/tokens.json. */\n:root{${Object.entries(
    tokens,
  )
    .map(([k, v]) => `--${k}:${v};`)
    .join("")}}`,
  { parser: "css" },
);
const master = `# ObjectScan premium design system\n\nSource: apps/web/src/lib/design-tokens/tokens.json. Generated by scripts/sync-design-system.mjs.\n\nProduct-first Korean creator service: midnight canvas, restrained teal actions, red reserved for the supplied mascot/destructive meaning. Choice A (Creator studio) wins over mascot-first B and gallery-first C because production entry and usable results remain primary; B hides the product and C has no real inventory yet. Meshy informs IA, never branding/assets/copy.\n\n## Semantic palette\n\n| CSS token | Value |\n|---|---|\n${Object.entries(
  tokens,
)
  .map(([k, v]) => `| \`--${k}\` | \`${v}\` |`)
  .join(
    "\n",
  )}\n\n## Type and rhythm\n\nSelf-hosted @fontsource-variable/noto-sans-kr. Korean-first, word-break:keep-all with overflow-wrap:anywhere for long content. Headings60/44/38/30/24; body16/15/14; utility12/11 only. 1.65 body leading, restrained negative heading tracking. Desktop page max1440, margins20–72. Spacing4/8/12/16/24/32/48/64; control radius10, panels20, grouped inset controls6. No decorative gradients/glow/glass or repeated feature-card trios.\n\n## States and motion\n\nButtons44px minimum, controls use control-border, primary text on-accent; focus2px focus token with4px offset. Press feedback1px, transitions180–200ms only for state/feedback. Reduced motion removes animation and smooth scrolling. Never show invented success, financial amounts or unavailable generation. Errors remain actionable Korean and files private.\n\n## Page density\n\nLanding: airy product preview, one primary creation intent, no WebGL on initial load. Create: progressive mode/file selection, memory-only draft handoff with explicit upload. Workspace: denser task surfaces and real queue states. Editor: dedicated canvas/tools, numeric alternatives, mobile bottom sheet. Marketplace: real listings only plus a clearly labeled non-sale public example. See pages/ overrides.\n\n## Recommendations reviewed\n\nUI UX Pro Max first query returned light Glassmorphism/blue-orange, incompatible with this brief; raw output retained in artifacts/design-v4/uipro-system.log and not adopted. Refined search and UX/Next.js searches inform keyboard, feedback, responsive and reduced-motion rules. This master records reviewed ObjectScan decisions, not unverified automatic defaults.\n`;
for (const [path, value] of [
  ["apps/web/src/app/design-tokens.css", css],
  [
    "design-system/objectscan/MASTER.md",
    await format(master, { parser: "markdown" }),
  ],
]) {
  if (process.argv.includes("--check")) {
    if ((await readFile(path, "utf8")) !== value)
      throw Error("Design token drift: " + path);
  } else await writeFile(path, value);
}
console.log("ObjectScan code/master token mapping verified");
